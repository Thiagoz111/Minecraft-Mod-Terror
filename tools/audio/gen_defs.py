"""Write sounds.json + ModSounds.java from sounds_def."""
import json, os
from sounds_def import SOUNDS, java_name
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sj = {}
for name, (n, es, en, stream) in SOUNDS.items():
    files = [f"deadline:{name.replace('.', '/')}" + (f"_{i+1}" if n > 1 else '') for i in range(n)]
    entry = {'subtitle': f'subtitles.deadline.{name}', 'sounds': []}
    for f in files:
        entry['sounds'].append({'name': f, 'stream': True} if stream else f)
    sj[name] = entry
# Java aliases (old constant -> event) kept while code still uses an old name; empty when nothing does
ALIASES = {}
VARIANT_EVENTS = ('spirit_box.voice',)  # also one event per file, so the code can pick the exact take
for name in VARIANT_EVENTS:
    n, es_, en_, stream = SOUNDS[name]
    for i in range(n):
        sj[f'{name}_{i + 1}'] = {'subtitle': f'subtitles.deadline.{name}', 'sounds': [f"deadline:{name.replace('.', '/')}_{i + 1}"]}
p = os.path.join(ROOT, 'src/main/resources/assets/deadline/sounds.json')
os.makedirs(os.path.dirname(p), exist_ok=True)
json.dump(sj, open(p, 'w'), indent=1, ensure_ascii=False)
lines = ['// GENERATED by tools/audio/gen_defs.py -- do not edit by hand.', 'package com.deadline.registry;', '',
         'import com.deadline.DeadLine;', 'import net.minecraft.core.Registry;', 'import net.minecraft.core.registries.BuiltInRegistries;',
         'import net.minecraft.resources.Identifier;', 'import net.minecraft.sounds.SoundEvent;', '', 'public final class ModSounds {']
for name in SOUNDS:
    lines.append(f'\tpublic static final SoundEvent {java_name(name)} = register("{name}");')
if ALIASES:
    lines.append('')
    lines.append('\t/** Transitional aliases (old names still used by code in progress): use the event they point to. */')
    for old, name in ALIASES.items():
        lines.append(f'\tpublic static final SoundEvent {old} = {java_name(name)};')
lines.append('')
lines.append('\t/** Single-file events of multi-take sounds, so a take can be chosen (e.g. the spirit box answer matching its subtitle). */')
lines.append('\tprivate static final java.util.Map<String, SoundEvent[]> VARIANTS = new java.util.HashMap<>();')
lines.append('\tstatic {')
for name in VARIANT_EVENTS:
    n = SOUNDS[name][0]
    lines.append(f'\t\tVARIANTS.put("{name}", new SoundEvent[] {{' + ', '.join(f'register("{name}_{i + 1}")' for i in range(n)) + '});')
lines.append('\t}')
lines.append('')
lines.append('\tpublic static SoundEvent variant(String name, int index) {')
lines.append('\t\tSoundEvent[] v = VARIANTS.get(name);')
lines.append('\t\treturn v == null || v.length == 0 ? null : v[Math.floorMod(index, v.length)];')
lines.append('\t}')
lines += ['', '\tprivate ModSounds() {', '\t}', '',
          '\tprivate static SoundEvent register(String name) {', '\t\tIdentifier id = DeadLine.id(name);',
          '\t\treturn Registry.register(BuiltInRegistries.SOUND_EVENT, id, SoundEvent.createVariableRangeEvent(id));', '\t}', '',
          '\tpublic static void init() {', '\t}', '}', '']
jp = os.path.join(ROOT, 'src/main/java/com/deadline/registry/ModSounds.java')
os.makedirs(os.path.dirname(jp), exist_ok=True)
open(jp, 'w').write('\n'.join(lines))
print(len(SOUNDS), 'sounds')
