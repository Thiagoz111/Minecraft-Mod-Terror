"""Write sounds.json + ModSounds.java from sounds_def."""
import json, os
from sounds_def import SOUNDS, LINE_EVENTS, java_name
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sj = {}
for name, (n, es, en, stream) in SOUNDS.items():
    files = [f"deadline:{name.replace('.', '/')}" + (f"_{i+1}" if n > 1 else '') for i in range(n)]
    entry = {'subtitle': f'subtitles.deadline.{name}', 'sounds': []}
    for f in files:
        entry['sounds'].append({'name': f, 'stream': True} if stream else f)
    sj[name] = entry
for name in LINE_EVENTS:  # spoken lines: subtitles are drawn by the mod's own subtitle bar, not vanilla's
    sj[name] = {'sounds': [f"deadline:{name.replace('.', '/')}"]}
p = os.path.join(ROOT, 'src/main/resources/assets/deadline/sounds.json')
os.makedirs(os.path.dirname(p), exist_ok=True)
json.dump(sj, open(p, 'w'), indent=1, ensure_ascii=False)
lines = ['// GENERATED by tools/audio/gen_defs.py -- do not edit by hand.', 'package com.deadline.registry;', '',
         'import com.deadline.DeadLine;', 'import net.minecraft.core.Registry;', 'import net.minecraft.core.registries.BuiltInRegistries;',
         'import net.minecraft.resources.Identifier;', 'import net.minecraft.sounds.SoundEvent;', '', 'public final class ModSounds {']
for name in SOUNDS:
    lines.append(f'\tpublic static final SoundEvent {java_name(name)} = register("{name}");')
lines.append('')
lines.append('\t/** Spoken lines (tools/audio/lines.py), looked up by id through {@link #line(String)}. */')
lines.append('\tprivate static final java.util.Map<String, SoundEvent> LINES = new java.util.HashMap<>();')
lines.append('\tstatic {')
for name in LINE_EVENTS:
    lines.append(f'\t\tLINES.put("{name[5:]}", register("{name}"));')
lines.append('\t}')
lines.append('')
lines.append('\tpublic static SoundEvent line(String id) {')
lines.append('\t\treturn LINES.get(id);')
lines.append('\t}')
lines += ['', '\tprivate ModSounds() {', '\t}', '',
          '\tprivate static SoundEvent register(String name) {', '\t\tIdentifier id = DeadLine.id(name);',
          '\t\treturn Registry.register(BuiltInRegistries.SOUND_EVENT, id, SoundEvent.createVariableRangeEvent(id));', '\t}', '',
          '\tpublic static void init() {', '\t}', '}', '']
jp = os.path.join(ROOT, 'src/main/java/com/deadline/registry/ModSounds.java')
os.makedirs(os.path.dirname(jp), exist_ok=True)
open(jp, 'w').write('\n'.join(lines))
print(len(SOUNDS), 'sounds')
